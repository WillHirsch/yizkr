"""Render the SPARQL query library and publish it to wiki pages.

The packaged ``*.rq`` files are templates: they reference the model
vocabulary by manifest key (``wdt:{P:instance_of}``, ``wd:{Q:human}``)
because local P/Q ids are per-instance and never live in the repo.
Rendering resolves the keys against the target instance and prepends
``PREFIX`` declarations bound to the instance's concept URI — the WDQS
build ships built-in prefixes pointing at wikidata.org, so without the
redeclaration every pattern silently matches nothing.

Each query is published to ``Project:Queries/<name>`` with the rendered
text, a "run" link into the query service UI, and an embeddable result
view link (ADR-0004 W1 exploration tier), plus a ``Project:Queries``
index page. Idempotent: pages are fully regenerated on every run.

CLI: `yizkr publish-queries [--dry-run]`.
"""

from __future__ import annotations

import re
import urllib.parse
from importlib.resources import files

from yizkr.core.config import Config
from yizkr.core.wiki import WikiClient

INDEX_PAGE = "Project:Queries"
PLACEHOLDER = re.compile(r"\{([PQ]):([a-z][a-z0-9_]*)\}")


def load_templates() -> dict[str, str]:
    """name -> template text, from the packaged *.rq files."""
    return {
        resource.name[: -len(".rq")]: resource.read_text()
        for resource in sorted(files("yizkr.queries").iterdir(), key=lambda r: r.name)
        if resource.name.endswith(".rq")
    }


def placeholder_keys(template: str) -> tuple[set[str], set[str]]:
    """(property keys, item keys) referenced by a template."""
    properties, items = set(), set()
    for kind, key in PLACEHOLDER.findall(template):
        (properties if kind == "P" else items).add(key)
    return properties, items


def render(template: str, properties: dict[str, str], items: dict[str, str]) -> str:
    def substitute(match: re.Match) -> str:
        kind, key = match.groups()
        table = properties if kind == "P" else items
        if key not in table:
            raise KeyError(
                f"template references unknown manifest "
                f"{'property' if kind == 'P' else 'item'} key {key!r}"
            )
        return table[key]

    return PLACEHOLDER.sub(substitute, template)


def prefix_block(concept_uri: str) -> str:
    """Explicit prefixes bound to THIS instance's concept URI."""
    return "\n".join(
        [
            f"PREFIX wd: <{concept_uri}/entity/>",
            f"PREFIX wdt: <{concept_uri}/prop/direct/>",
            f"PREFIX p: <{concept_uri}/prop/>",
            f"PREFIX ps: <{concept_uri}/prop/statement/>",
            f"PREFIX pq: <{concept_uri}/prop/qualifier/>",
            f"PREFIX pr: <{concept_uri}/prop/reference/>",
            "PREFIX wikibase: <http://wikiba.se/ontology#>",
            "PREFIX prov: <http://www.w3.org/ns/prov#>",
            "PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>",
            "PREFIX bd: <http://www.bigdata.com/rdf#>",
            "",
        ]
    )


def render_for_instance(
    template: str, properties: dict[str, str], items: dict[str, str], concept_uri: str
) -> str:
    return prefix_block(concept_uri) + render(template, properties, items)


def description_of(template: str) -> str:
    """Leading comment block, minus display directives like #defaultView."""
    lines = []
    for line in template.splitlines():
        if not line.startswith("#"):
            break
        if line.startswith("#defaultView"):
            continue
        lines.append(line.lstrip("# ").rstrip())
    return " ".join(lines).strip()


def page_title(name: str) -> str:
    return f"{INDEX_PAGE}/{name}"


def page_wikitext(name: str, template: str, rendered: str, frontend: str) -> str:
    encoded = urllib.parse.quote(rendered, safe="")
    return "\n".join(
        [
            f"''Generated by <code>yizkr publish-queries</code> from "
            f"<code>queries/{name}.rq</code> — do not edit by hand; re-run "
            f"the publisher to refresh.''",
            "",
            description_of(template),
            "",
            f"'''[{frontend}/#{encoded} ▶ Run this query]''' · "
            f"[{frontend}/embed.html#{encoded} embeddable result view]",
            "",
            '<syntaxhighlight lang="sparql">',
            rendered.rstrip(),
            "</syntaxhighlight>",
            "",
        ]
    )


def index_wikitext(templates: dict[str, str]) -> str:
    lines = [
        "''Generated by <code>yizkr publish-queries</code> — do not edit by "
        "hand.'' The query library lives in the project repository under "
        "<code>src/yizkr/queries/</code>; queries reference the model "
        "vocabulary resolved for this instance (see "
        "[[Project:Model mapping]]).",
        "",
    ]
    for name, template in templates.items():
        lines.append(f"* [[{page_title(name)}|{name}]] — {description_of(template)}")
    lines.append("")
    return "\n".join(lines)


def publish_queries(
    client: WikiClient, config: Config, dry_run: bool = False, log=print
) -> list[str]:
    """Render and publish every packaged query. Returns page titles."""
    templates = load_templates()
    if not templates:
        raise SystemExit("no *.rq templates packaged with yizkr.queries")
    if not config.wdqs_url:
        raise SystemExit(
            "WDQS_PUBLIC_HOST is not configured; needed for run/embed links."
        )
    properties, items = client.vocabulary()
    published: list[str] = []

    for name, template in templates.items():
        rendered = render_for_instance(template, properties, items, config.concept_uri)
        if dry_run:
            log(f"--- {page_title(name)} (dry run) ---")
            log(rendered)
            continue
        client.edit_page(
            page_title(name),
            page_wikitext(name, template, rendered, config.wdqs_url),
            summary="query library: refresh from repo",
        )
        published.append(page_title(name))
        log(f"published {page_title(name)}")

    if not dry_run:
        client.edit_page(
            INDEX_PAGE,
            index_wikitext(templates),
            summary="query library: refresh index",
        )
        published.append(INDEX_PAGE)
        log(f"published {INDEX_PAGE}")
    return published
